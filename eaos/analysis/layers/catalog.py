def sentence(rule, params, language='en'):
    """The sentence of one finding in a language; a missing value is left as its name, never a crash."""
    _, _, english, arabic, *_ = RULES[rule]
    return (arabic if language == 'ar' else english).format_map(_Keep(params))


def fix(rule, params, language='en'):
    return RULES[rule][5 if language == 'ar' else 4].format_map(_Keep(params))


class _Keep(dict):
    def __missing__(self, key): return '{' + key + '}'
