"""What the project declared out of scope for analysis.

Reading a declared field is extraction, not policy interpretation, so it belongs in this layer:
every collector gets the same answer without the facts layer depending on the ledger.

A vendored directory is one whose contents were copied in from elsewhere and are not the
reader's code. The fact that a vendored dependency is in the tree does not turn the audit
into an audit of that dependency: the reader wants a report about their code. By default
the engine excludes a small set of well-known vendored directory names; a project that
genuinely wants them analysed declares `include_vendored: true` in `eaos.policy.json`.
"""
import subprocess
from pathlib import Path
from ..core.system.files import read_json

FILENAME = 'eaos.policy.json'
# .claude/worktrees: the working copies an AI assistant makes of the project inside it, whole copies of its code.
VENDORED = ("testdata", "fixtures", "vendor", "node_modules", "third_party",
            "generated", ".venv", "dist", "build", "components/ui", ".claude/worktrees")

# Generated files, excluded in any project and whatever the policy: minified and bundled scripts and styles. A
# bundle with another name is caught by its text (Source.generated): lines no person writes.
GENERATED = ('*.min.js', '*.min.mjs', '*.min.cjs', '*.min.css', '*.bundle.js', '*.chunk.js')
GENERATED_REASON = 'minified or bundled output: generated by a build, not written by hand'


def _analysis(target, path=None):
    """The policy's `analysis` section; {} when the project has none or its policy does not read."""
    candidate = Path(path) if path else Path(target) / FILENAME
    if not candidate.is_file(): return {}
    policy = read_json(candidate)
    analysis = policy.get('analysis') if isinstance(policy, dict) else None
    return analysis if isinstance(analysis, dict) else {}


def _include_vendored(target, path=None):
    """True when the project's policy says vendored paths are part of the analysis."""
    return bool(_analysis(target, path).get('include_vendored'))


def _declared(target, path=None, strict=False):
    """The paths the policy's analysis.exclude names; a malformed list raises when `strict`, else counts as none."""
    patterns = _analysis(target, path).get('exclude') or []
    if not isinstance(patterns, list) or not all(isinstance(item, str) for item in patterns):
        if strict: raise ValueError('analysis.exclude must be an array of path patterns')
        return []
    return sorted({item.strip('/') for item in patterns if item.strip('/')})


def declared_exclusions(target, path=None):
    """Paths the project declares and the vendored defaults the engine applies.

    Silent exclusion is forbidden: every entry carries a reason the summary must surface.
    """
    declared = _declared(target, path, strict=True)
    vendored = [] if _include_vendored(target, path) else list(VENDORED)
    # The minified-file patterns (GENERATED) are file globs, applied by facts/source.py itself; the engines receive
    # folder names, and a glob there broke Checkov (it reads --skip-path as a regular expression).
    return sorted({*declared, *vendored, *git_ignored(target)})


def vendored_patterns():
    """The default vendored directory names the engine excludes unless the project opts in."""
    return list(VENDORED)


def git_ignored(target):
    """What the project's own .gitignore keeps out of its repository: build outputs, local data, copies.

    A snapshot handed over as an archive carries them (a full-stack app shipped release/, dist/ and .data/ beside
    its source, 756 files, and release/ is a second copy of the server). They are not the project's code,
    so analysing them counts every duplicate and dead symbol twice. Empty when the target is not a git
    repository or git is absent: then nothing is excluded on this ground."""
    try:
        done = subprocess.run(['git', '-C', str(target), 'ls-files', '--others', '--ignored', '--exclude-standard', '--directory'],
                              capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired):
        return []
    if done.returncode != 0: return []
    return sorted({line.strip().rstrip('/') for line in done.stdout.splitlines() if line.strip().rstrip('/')})


def exclusion_reasons(target, path=None):
    """For every exclusion pattern, the reason the engine applied it.

    Used by the summary that must surface every exclusion; never returns an entry without
    a reason attached.
    """
    reasons = dict.fromkeys(_declared(target, path), 'declared in eaos.policy.json analysis.exclude')
    if not _include_vendored(target, path):
        for pattern in VENDORED:
            reasons.setdefault(pattern, 'vendored directory name; opt in via analysis.include_vendored=true')
    for pattern in GENERATED:
        reasons.setdefault(pattern, GENERATED_REASON)
    reasons.setdefault('(long lines)', 'a script or stylesheet with a line of over 1000 characters: ' + GENERATED_REASON)
    for pattern in git_ignored(target):
        reasons.setdefault(pattern, "ignored by the project's .gitignore: not part of its repository")
    return reasons
