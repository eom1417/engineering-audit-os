"""The behaviour lock's specs, written before anything changes (eaos/live/behavior_lock.py runs them): a spec for every
feature in its own tool's format under behavior-lock/ in the report, Playwright for its pages and http routes,
ApprovalTests for the public interface of its import-safe Python modules. Generation is static: nothing from the
project runs here."""
import ast
import json
import re
from pathlib import Path

PAGE, HTTP = 'page', 'http'
# A route no browser holding a session calls (the lock, the probe, the crawl): it would end the session, or change data.
LEAVES = r'(log|sign)[-_ ]?(out|off)|logout|delete|remove|destroy|unsubscribe|deactivate'
PARAM = re.compile(r'\$(\w+)|:(\w+)|\{(\w+)(?::[^}]*)?\}')       # TanStack $id, Express :id, Starlette {id} / {id:int}
SAFE = (ast.Import, ast.ImportFrom, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef, ast.Assign, ast.AnnAssign)
REQUIREMENTS = 'approvaltests==19.1.1\npytest==9.1.1\n'

CONFIG = """import path from 'node:path';
import { defineConfig, devices } from '@playwright/test';

// Generated by EAOS. BASE_URL points at the running application; nothing here names a host.
export default defineConfig({
  testDir: './playwright',
  snapshotPathTemplate: '{testDir}/../__screenshots__/{testFilePath}/{arg}{ext}',
  // The raw Playwright report; NS26 turns a run into behavior-lock/results.json, the contract artifact.
  reporter: [['json', { outputFile: 'playwright-report.json' }]],
  use: { baseURL: process.env.BASE_URL, storageState: path.join(__dirname, '.auth', 'user.json') },
  projects: [
    { name: 'setup', testMatch: /auth\\.setup\\.ts/ },
    { name: 'lock', dependencies: ['setup'], use: { ...devices['Desktop Chrome'] } },
  ],
});
"""

AUTH = """import fs from 'node:fs';
import path from 'node:path';
import { test as setup } from '@playwright/test';

// Generated by EAOS. Signs in once when the owner granted E2E_USER and E2E_PASSWORD; otherwise the lock
// runs signed out. E2E_LOGIN_PATH overrides the sign-in page when it is not /login.
const file = path.join(__dirname, '..', '.auth', 'user.json');

setup('sign in once, if credentials were granted', async ({ page }) => {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const user = process.env.E2E_USER;
  const password = process.env.E2E_PASSWORD;
  if (!user || !password) {
    fs.writeFileSync(file, JSON.stringify({ cookies: [], origins: [] }));
    setup.skip(true, 'no E2E_USER and E2E_PASSWORD: the lock runs signed out');
    return;
  }
  await page.goto(process.env.E2E_LOGIN_PATH ?? '/login');
  await page.locator('input[type="email"], input[name="email"], input[name="username"]').first().fill(user);
  await page.locator('input[type="password"]').first().fill(password);
  await page.locator('button[type="submit"], input[type="submit"]').first().click();
  await page.waitForLoadState('networkidle');
  await page.context().storageState({ path: file });
});
"""


def slug(text, limit=80):
    """A file-name part from any text; a long one is cut and keeps a short hash, so it never exceeds a file name."""
    out = re.sub(r'[^a-z0-9]+', '-', str(text).lower()).strip('-') or 'root'
    if len(out) <= limit: return out
    import hashlib
    return out[:limit - 9].rstrip('-') + '-' + hashlib.sha256(out.encode('utf-8')).hexdigest()[:8]


def surfaces(out):
    """{route: (surface kind, http method, file)} from the entry-point facts."""
    try: facts = json.loads((Path(out) / 'facts/entrypoints.json').read_text(encoding='utf-8'))['facts']
    except (OSError, ValueError, KeyError): return {}
    found = {}
    for fact in facts:
        value = fact.get('value') or {}
        if fact.get('kind') == 'entry_point' and value.get('route'):
            row = (value.get('surface'), (value.get('http_method') or 'GET').upper(), (fact.get('location') or {}).get('path'))
            found.setdefault(value['route'], row)
            # A command's feature names it by its file (run_app.py), not by its route (run_app).
            if value.get('surface') == 'cli' and row[2]: found.setdefault(row[2], row)
    return found


def kind_of(surface, known):
    """page, http or cli: from the entry-point facts; a surface they do not know is a page only if it is a URL."""
    if surface in known: return known[surface]
    return (PAGE if surface.startswith('/') or surface == '*' else 'cli', 'GET', None)


def crawled_pages(out):
    """The distinct pages the crawl opened (live/crawl.json, the first address of each template), standing in for the
    app's pages only when its code names none: an SPA with no client router (one Workspace.tsx, what EAOS's own
    blueprint builds) has no page in its entry-point facts, yet its running pages were found and pictured; a real
    check then locked, walked and loaded nothing. [] otherwise, or before the crawl ran."""
    if PAGE in {row[0] for row in surfaces(out).values()}: return []
    try: return list(json.loads((Path(out) / 'live/crawl.json').read_text(encoding='utf-8')).get('pages') or [])
    except (OSError, ValueError): return []


def features_of(out):
    """features.json's features, plus one per crawled page standing in for the code's (crawled_pages): what the lock,
    the journeys and the load read as the program's surfaces. One each, so a page that differs between two recordings
    (a clock, a random tip) is refused alone: in one shared spec it failed every page, and the safety net locked none."""
    try: features = json.loads((Path(out) / 'features.json').read_text(encoding='utf-8'))['features']
    except (OSError, ValueError, KeyError): features = []
    return features + [{'name': f'page {page}', 'description': 'A page of the running app, found by the crawl', 'critical': False,
                        'surfaces': [page], 'tables': [], 'files': []} for page in crawled_pages(out)]


def path_of(route):
    """The URL a route id is served at, or None for a layout that has no URL of its own.

    TanStack Router ids name files, not URLs: a segment starting with `_` is a pathless layout and is not in
    the URL; a trailing `_` only un-nests the route (`cartoes_/faturas` is served at `/cartoes/faturas`);
    `(group)` segments (Next.js) are not in the URL either."""
    if route == '__root__': return None
    parts = [part for part in route.split('/') if part]
    if parts and parts[-1].startswith('_') and not parts[-1].startswith('__'): return None
    kept = [part.rstrip('_') if part.endswith('_') and not part.startswith('$') else part
            for part in parts if not (part.startswith('_') or (part.startswith('(') and part.endswith(')')))]
    return '/' + '/'.join(kept)


def url(route):
    """A route as a TypeScript template literal, parameters read from E2E_<PARAM>; and the parameters."""
    if route == '*': return '`/__eaos_unknown_route__`', []
    route = path_of(route) or route
    params = [next(filter(None, names)) for names in PARAM.findall(route)]
    literal = PARAM.sub(lambda m: '${process.env.E2E_' + next(filter(None, m.groups())).upper() + " ?? ''}", route)
    return '`' + literal.replace('`', '\\`') + '`', params


# A journey run (run_journeys) sets EAOS_RRWEB to rrweb's bundle: once each page has loaded, the bundle is added to it
# and records it, and the events are kept beside the trace; the lock's own runs leave both variables unset, and these
# hooks do nothing. (Given to the page before it exists, rrweb 2.1.7 recurses until the stack overflows.)
JOURNEY_HOOKS = [
    "  test.beforeEach(async ({ page }) => {",
    "    const rrweb = process.env.EAOS_RRWEB;",
    "    if (!rrweb) return;",
    "    page.on('load', () => page.addScriptTag({ path: rrweb })",
    "      .then(() => page.evaluate(() => { const w = window as any; w.__eaosEvents = [];",
    "        w.rrweb.record({ emit: (event: unknown) => w.__eaosEvents.push(event) }); }))",
    "      .catch(() => {}));",
    "  });",
    "  test.afterEach(async ({ page }, info) => {",
    "    if (!process.env.EAOS_RRWEB || !process.env.EAOS_JOURNEYS) return;",
    "    const events = await page.evaluate(() => (window as any).__eaosEvents ?? []).catch(() => []);",
    "    fs.writeFileSync(path.join(process.env.EAOS_JOURNEYS, `${info.testId}.rrweb.json`),",
    "                     JSON.stringify({ title: info.titlePath.slice(1).join(' > '), events }));",
    "  });",
]


def playwright_spec(feature, rows):
    """The spec text of a feature's pages and http routes, and the plan's surface list."""
    lines = ["import fs from 'node:fs';", "import path from 'node:path';", "import { test, expect } from '@playwright/test';", '',
             f"// Generated by EAOS from features.json: what \"{feature['name']}\" does today. The first run on the",
             '// original code records the snapshots; every later run must match them.', '',
             f"test.describe({json.dumps(feature['name'])}, () => {{"]
    if any(kind != HTTP for _, (kind, _, _) in rows): lines += JOURNEY_HOOKS
    listed = []
    for route, (kind, method, _) in rows:
        entry, test = _route_test(route, kind, method)
        listed.append(entry)
        lines += test
    lines += ['});', '']
    return '\n'.join(lines), listed


def _route_test(route, kind, method):
    """(the plan's entry of one route, its test lines): a layout gets none, a route that writes or signs out is skipped
    (a GET /logout run with the session ended it for every page stage after the lock: they saw the sign-in page)."""
    if route != '*' and path_of(route) is None: return f'{route} (layout: no URL of its own)', []
    if re.search(LEAVES, route, re.I):
        return f'{route} (ends the session or changes data: not called)', [
            f"  test({json.dumps(f'{route} is not called')}, async () => {{", "    test.skip(true, 'it would sign out or change data');", '  });']
    if kind == HTTP and method != 'GET':
        return f'{method} {route} (needs_fixture: writes)', [
            f"  test({json.dumps(f'{method} {route} is not called blindly')}, async () => {{",
            f"    test.skip(true, 'needs_fixture: {method} writes; lock it against a fixture');", '  });']
    target, params = url(route)
    # Named by the URL, not the route id: moving a file between layouts must not orphan its recording.
    name = slug(path_of(route) or route) if route != '*' else 'unknown-route'
    guard = [f"    test.skip(!process.env.E2E_{p.upper()}, 'needs_fixture: set E2E_{p.upper()}');" for p in params]
    entry = ('GET ' if kind == HTTP else '') + route + (' (needs_fixture)' if params else '')
    return entry, _request_test(route, target, name, guard) if kind == HTTP else _page_test(route, target, name, guard)


def _request_test(route, target, name, guard):
    return [f"  test({json.dumps(f'GET {route} answers as it does today')}, async ({{ request }}) => {{", *guard,
            f"    const response = await request.get({target});",
            f"    expect(String(response.status())).toMatchSnapshot('{name}.status.txt');", '  });']


def _page_test(route, target, name, guard):
    return [f"  test({json.dumps(f'{route} renders as it does today')}, async ({{ page }}) => {{", *guard,
            '    const messages: string[] = [];',
            "    page.on('pageerror', (error) => messages.push(`pageerror: ${error.message}`));",
            "    page.on('console', (message) => { if (message.type() === 'error') messages.push(`console: ${message.text()}`); });",
            # The clock held still: a screen showing the time differs between two recordings (HungerLab's "now").
            "    await page.clock.setFixedTime(new Date('2026-01-01T09:00:00Z'));",
            f'    await page.goto({target});',
            "    await page.waitForLoadState('networkidle');",
            "    await page.waitForFunction(() => document.body.innerText.trim().length > 0, null, { timeout: 60000 }).catch(() => {});",
            f"    expect(messages.join('\\n')).toMatchSnapshot('{name}.console.txt');",
            f"    await expect(page).toHaveScreenshot('{name}.png', {{ fullPage: true, maxDiffPixelRatio: 0.01 }});",
            '  });']


def import_safe(path):
    """Whether importing the file only defines things: no top-level statement that runs code."""
    try: tree = ast.parse(Path(path).read_text(encoding='utf-8', errors='replace'))
    except (OSError, SyntaxError): return False
    for node in tree.body:
        if isinstance(node, SAFE): continue
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant): continue   # a docstring
        if isinstance(node, ast.If) and 'name' in ast.dump(node.test) and '__main__' in ast.dump(node.test): continue
        if isinstance(node, ast.Try) and all(isinstance(n, (ast.Import, ast.ImportFrom)) for n in node.body): continue
        return False
    return True


def approval_test(feature, target):
    modules = sorted({f[:-3].replace('/', '.') for f in feature.get('files') or []
                      if f.endswith('.py') and not f.split('/')[-1].startswith('test_') and import_safe(Path(target) / f)
                      and not f.endswith('__init__.py')})
    if not modules: return None, []
    text = '\n'.join([
        f'"""Generated by EAOS: the public interface of "{feature["name"]}" as it is today, approved on the original code."""',
        'import importlib', 'import inspect', 'import os', 'import re', '', 'from approvaltests import verify', '',
        f'MODULES = {json.dumps(modules, indent=4)}', '', '',
        'def public_interface():',
        '    lines = []',
        '    for name in MODULES:',
        '        module = importlib.import_module(name)',
        '        for attribute in sorted(n for n in vars(module) if not n.startswith("_")):',
        '            value = getattr(module, attribute)',
        '            if (inspect.isfunction(value) or inspect.isclass(value)) and getattr(value, "__module__", None) == name:',
        '                try: signature = str(inspect.signature(value))',
        '                except (TypeError, ValueError): signature = "(...)"',
        '                lines.append(f"{name}.{attribute}{signature}")',
        '    # What differs between two runs of the same code is left out: where the copy is, and where an object lives.',
        '    return re.sub(r" at 0x[0-9a-fA-F]+", "", "\\n".join(lines)).replace(os.getcwd(), "<root>")', '', '',
        'def test_the_public_interface_is_as_it_was():',
        '    verify(public_interface())', ''])
    return text, modules


def build(out, target):
    """Write behavior-lock/ and return its plan (behavior-lock/plan.json, schemas/artifacts/behavior-lock-plan)."""
    out, target = Path(out), Path(target)
    features, known = features_of(out), surfaces(out)
    root = out / 'behavior-lock'
    specs = [feature_spec(feature, known, target, root) for feature in features]
    if any(spec['path'].startswith('playwright/') for spec in specs):
        (root / 'playwright.config.ts').write_text(CONFIG, encoding='utf-8')
        (root / 'playwright/auth.setup.ts').write_text(AUTH, encoding='utf-8')
    if any(spec['path'].startswith('approvals/') for spec in specs):
        (root / 'approvals/requirements.txt').write_text(REQUIREMENTS, encoding='utf-8')
    plan = {'schema_version': 1, 'specs': specs}
    if specs:
        root.mkdir(parents=True, exist_ok=True)
        (root / 'plan.json').write_text(json.dumps(plan, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
    return plan


def feature_spec(feature, known, target, root):
    """The plan's row for one feature, its spec written under `root`: Playwright when one of its pages or http routes
    has a URL, else ApprovalTests for its import-safe modules, else listed without a spec. A feature of layouts only
    gets no Playwright spec: one without a test makes Playwright refuse the whole run ("No tests found")."""
    rows = [(route, kind_of(route, known)) for route in feature.get('surfaces') or []]
    web = [(route, info) for route, info in rows if info[0] in (PAGE, HTTP)]
    if any(route == '*' or path_of(route) is not None for route, _ in web):
        text, listed = playwright_spec(feature, web)
        return _written(root, f'playwright/{slug(feature["name"])}.spec.ts', text, feature, 'playwright', listed)
    text, modules = approval_test(feature, target)
    if text:
        return _written(root, f'approvals/test_{slug(feature["name"]).replace("-", "_")}.py', text, feature, 'approvaltests', modules)
    return _unlocked(feature, web)


def _unlocked(feature, web):
    """The plan's row for a feature with nothing to run: its surfaces, each with why."""
    if web: return {'feature': feature['name'], 'tool': 'playwright', 'path': '', 'surfaces': playwright_spec(feature, web)[1]}
    return {'feature': feature['name'], 'tool': 'approvaltests', 'path': '',
            'surfaces': [f'{s} (needs_fixture: no web surface and no import-safe module)' for s in feature.get('surfaces') or []]}


def _written(root, path, text, feature, tool, listed):
    (root / path).parent.mkdir(parents=True, exist_ok=True)
    (root / path).write_text(text, encoding='utf-8')
    return {'feature': feature['name'], 'tool': tool, 'path': path, 'surfaces': listed}
